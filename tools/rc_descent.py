"""
The single-piece step of r9 Response 15 (descent over strict subdivisions),
executable. notes/rc-generator.md §4 and §7.

Input: parallel raw terms t, u : A of rank n in a finite strong-Steiner
context G, with equal strict value 1^{n-h} c, c intrinsic of rank h < n and
composite. Sd(c) is computed by steiner.Sd.

For theta in Sd(c) the piece U_theta is read off by the literal expansion
of Response 15: a head all of whose substitution entries have strict labels
in theta (the subcategory generated by theta) is expanded; any other
subterm is a generator, and must have a label in theta of proper support.
If both t and u lie in one piece U_theta, then (no gluing is needed):

  1. W = the pasting context of the globular arity theta, each variable
     labelled by its strict cell.
  2. J : W -> G, variable by variable in order: the low objects literally,
     every other variable a generator of t or u with that label at the
     already assigned faces (target face of t first), else a word lift
     (rc_lift.lift_at) at those faces.
  3. R : U_theta -> W: expanded heads keep their head, a generator is sent
     to the lift in W of the W-cell over its label (unique: torsion-free
     complexes have monic arities) at the images of its faces.
  4. R(t), R(u) are parallel in the pasting context W with equal strict
     image: compared there (globular, Response 2), then J gives
     w* : JR(t) -> JR(u).
  5. Bridges: for each generator x with JR(x) != x, the cylinder
     x^ : a_x -> b_x (rc_nat conventions, x+ = JR(x)) is an equal-image
     comparison on the proper support of the label of x (a recursive call).
     The generators, their copies and bridges form an abstract context H in
     which t and u are terms; rc_nat.square and rc_nat.nat_op give the lax
     square of t and the oplax square of u.
  6. Transfer (step 2 of Response 15): when the target face of t is not
     moved (J was chosen from it), t -> s^ * t* -> s^ * u* -> u.

Every result is type-checked by catt.infer; the trusted checker is Agda.
Gluing across several pieces (the rules D(P) over Campion's projections)
is not implemented: piece() returns None when no single piece holds both.
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from catt import *
import steiner as St

DEBUG = [False]
def _dbg(k):
    if DEBUG[0]:
        print('rc_descent.piece: None at', k)

class NoPiece(Exception):
    pass

def _R():
    import rc_oracle
    return rc_oracle

def _lab(G, x):
    return St.base_cell(St.image_to_cell(_R().strict_image(G, x)))

# ---------------------------------------------------------------- the arity

def _total(tr):
    return tr[1]

def _shape(tr):
    return () if tr[0] == 'leaf' else tuple(_shape(c) for c in tr[2])

def arity_ctx(tl):
    """The pasting context of a globular arity (steiner tree list) and the
    strict label of each of its variables, in tree_ctx order."""
    P = tree_ctx(tuple(_shape(x) for x in tl))
    labs = [St.base_cell(St.kface(_total(tl[0]), 0, '-'))]
    def emit(children, k):
        for ch in children:
            g = _total(ch)
            labs.append(St.base_cell(St.kface(g, k, '+')))
            if ch[0] == 'leaf':
                labs.append(St.base_cell(g))
            else:
                labs.append(St.base_cell(St.kface(g, k + 1, '-')))
                emit(ch[2], k + 1)
    emit(tl, 0)
    assert len(labs) == len(P)
    return P, labs

def _functor(W, labs, h):
    """{label in G: base cell of W} for the cells of W through rank h."""
    KW = St.Complex(W)
    def Fch(chain):
        out = ()
        for x, m in chain:
            d = tdim(W[x]) + 1
            out = St.ch_add(out, labs[x][d][0], m)
        return out
    table = {}
    for w in St.cells_upto(KW, set(range(len(W))), h):
        w = St.base_cell(w)
        img = St.base_cell(tuple((Fch(a), Fch(b)) for a, b in w))
        if img in table and table[img] != w:
            raise NoPiece('arity labelling not monic')
        table[img] = w
    return table

# ---------------------------------------------------------------- the step

def descend(G, A, t, u):
    """The comparison with the descent as its recursion (Response 15): the
    oracle first, then the single-piece step, whose own calls (bridges,
    in-arity comparisons, naturality fillers) recurse here."""
    from rc_oracle import rc
    w = rc(G, A, t, u)
    if w is None and tdim(A) >= 1:
        w = piece(G, A, t, u, descend)
    return w


def piece(G, A, t, u, rec, choose=None):
    import rc_nat
    try:
        return _piece(G, A, t, u, rec, choose)
    except (rc_nat.NoFiller, NoPiece, IndexError, KeyError, ValueError, AssertionError, TypeError_) as e:
        _dbg('exception %r' % (e,))
        return None

def _piece(G, A, t, u, rec, choose=None):
    R = _R()
    n = tdim(A) + 1
    K = St.Complex(G)
    c = _lab(G, t)
    if _lab(G, u) != c:
        _dbg(107)
        return None
    h = St.intrinsic_rank(c)
    if h < 1 or h >= n:
        _dbg(110)
        return None
    S = St.support(K, c)
    elems, _ = St.Sd(K, c)
    lab_memo = {}
    def lab(x):
        r = lab_memo.get(x)
        if r is None:
            r = lab_memo[x] = _lab(G, x)
        return r
    def expanded(x, gen):
        return x[0] == 'coh' and all(lab(e) in gen for e in x[3])
    def in_U(x, gen, memo):
        if x in memo:
            return memo[x]
        l = lab(x)
        if l not in gen:
            r = False
        elif St.support(K, l) != S:
            r = True
        elif expanded(x, gen):
            r = all(in_U(e, gen, memo) for e in x[3])
        else:
            r = False
        memo[x] = r
        return r
    cands = [(tl, gen) for tl, gen in elems if in_U(t, gen, {}) and in_U(u, gen, {})]
    if choose is not None:
        cands = [cands[choose]]
    if not cands:
        _dbg(139)
        return None
    tl, gen = min(cands, key=lambda e: len(e[1]))
    W, labs = arity_ctx(tl)
    Finv = _functor(W, labs, h)

    # generators of t and u in dependency order, the target face of t first
    gens, seen = [], set()
    def collect(x):
        if x in seen:
            return
        seen.add(x)
        if expanded(x, gen):
            for e in x[3]:
                collect(e)
            return
        if tdim_tm(G, x) > 0:
            B = infer(G, x)
            collect(B[2]); collect(B[3])
        gens.append(x)
    for x in (A[3], A[2], t, u):
        collect(x)
    for x in gens:
        if St.support(K, lab(x)) == S:
            raise NoPiece('full-support generator')

    # J : W -> G
    J = []
    for i, B in enumerate(W):
        L = labs[i]
        if B == STAR:
            (a, _), = L[0][0]
            J.append(v(a))
            continue
        s_, t_ = J[B[2][1]], J[B[3][1]]
        pick = None
        for x in gens:
            if lab(x) == L and infer(G, x)[2:] == (s_, t_):
                pick = x
                break
        if pick is None:
            import rc_lift
            pick = rc_lift.lift_at(G, L, s_, t_, rec, K)
        J.append(pick)
    Jsub = tuple(J)
    Jrev = {}
    for i, x in enumerate(J):
        Jrev.setdefault(x, i)

    # R : U_theta -> W
    Rm = {}
    def Rof(x):
        if x in Rm:
            return Rm[x]
        if expanded(x, gen):
            r = ('coh', x[1], x[2], tuple(Rof(e) for e in x[3]))
        elif x in Jrev and labs[Jrev[x]] == lab(x):
            r = v(Jrev[x])
        else:
            d = tdim_tm(G, x)
            wc = Finv.get(lab(x))
            if wc is None:
                raise NoPiece('label outside the arity')
            if d == 0:
                (a, _), = wc[0][0]
                r = v(a)
            else:
                B = infer(G, x)
                import rc_lift
                r = rc_lift.lift_at(W, St.raise_to(wc, d), Rof(B[2]), Rof(B[3]), rec)
        Rm[x] = r
        return r
    Rt, Ru = Rof(t), Rof(u)
    AW = infer(W, Rt)
    if infer(W, Ru) != AW:
        _dbg(213)
        return None
    wW = rec(W, AW, Rt, Ru)
    if wW is None:
        _dbg(216)
        return None
    JR = lambda x: subst_tm(Rof(x), Jsub)
    ts, us, wst = subst_tm(Rt, Jsub), subst_tm(Ru, Jsub), subst_tm(wW, Jsub)

    # the abstract context H: generators, and for moved ones x+ and x^
    import rc_nat
    Y = [x for x in gens if JR(x) != x]
    Hctx, Hv, sub = [], {}, []
    plus_map, up_map = {}, {}
    def ab(x):
        if x in Hv:
            return v(Hv[x])
        assert expanded(x, gen)
        return ('coh', x[1], x[2], tuple(ab(e) for e in x[3]))
    def ab_ty(B):
        if B == STAR:
            return B
        return arr(ab_ty(B[1]), ab(B[2]), ab(B[3]))
    Yset = set()
    def plus(w):
        if w[0] == 'v':
            return plus_map.get(w[1], w)
        return ('coh', w[1], w[2], tuple(plus(e) for e in w[3]))
    Yv = set(Y)
    for x in gens:
        Hv[x] = len(Hctx); Hctx.append(ab_ty(infer(G, x))); sub.append(x)
        if x not in Yv:
            continue
        i = Hv[x]
        Yset.add(i)
        p = len(Hctx); Hctx.append(_plus_ty(Hctx[i], plus)); sub.append(JR(x))
        plus_map[i] = v(p)
        Ht = tuple(Hctx)
        Yf = frozenset(Yset)
        meets = lambda w: bool(fv_tm(w) & Yf)
        lift = lambda w: rc_nat.nat_in(Ht, Yf, plus_map, up_map, w, rec)
        a, b = rc_nat.boundary_ab(Ht, v(i), meets, lift, plus)
        Ba = infer(Ht, a)
        Hctx.append(arr(Ba, a, b))
        up_map[i] = v(len(Hctx) - 1)
        st = tuple(sub)
        aG, bG = subst_tm(a, st), subst_tm(b, st)
        br = rec(G, infer(G, aG), aG, bG)
        if br is None:
            _dbg(260)
            return None
        sub.append(br)
    H = tuple(Hctx)
    sH = tuple(sub)
    Yf = frozenset(Yset)
    T, U = ab(t), ab(u)
    wt, at, bt = rc_nat.square(H, Yf, plus_map, up_map, T, rec)
    wu, au, bu = rc_nat.nat_op(H, Yf, plus_map, up_map, U, rec)
    wt, wu = subst_tm(wt, sH), subst_tm(wu, sH)
    at, bt, au, bu = (subst_tm(x, sH) for x in (at, bt, au, bu))
    meets = lambda w: bool(fv_tm(w) & Yf)
    lift = lambda w: subst_tm(rc_nat.nat_in(H, Yf, plus_map, up_map, w, rec), sH)
    # b-side: the same whiskers as b_t, around w* instead of t*
    mid = wst
    for j in range(n):
        w_ = rc_nat._iter_src_then(H, T, n - j)
        if meets(w_):
            mid = comp2(G, j, lift(w_), mid)
    X = comp2(G, n, comp2(G, n, wt, mid), wu)          # a_t -> a_u
    # a-side: a_t = (...(t *_0 A_0) ... ) *_{n-1} A_{n-1}; strip from the top
    As = []
    for j in range(n):
        w_ = rc_nat._iter_tgt(H, T, n - j)
        As.append(lift(w_) if meets(w_) else None)
    lo_t, lo_u = [t], [u]
    for j in range(n):
        if As[j] is not None:
            lo_t.append(comp2(G, j, lo_t[-1], As[j]))
            lo_u.append(comp2(G, j, lo_u[-1], As[j]))
        else:
            lo_t.append(lo_t[-1]); lo_u.append(lo_u[-1])
    assert lo_t[-1] == at and lo_u[-1] == au
    V = X
    for j in range(n - 1, -1, -1):
        if As[j] is None:
            continue
        a_, b_ = lo_t[j], lo_u[j]
        if j == n - 1:
            V = strip_right(G, n, a_, b_, As[j], V, rec)
        elif j == n - 2:
            V = strip_lower(G, n, a_, b_, As[j], V, rec)
        else:
            V = None
        if V is None:
            _dbg('strip at cut %d' % j)
            return None
    w = V
    assert infer(G, w) == arr(A, t, u), 'ill-typed piece comparison'
    return w

# ---------------------------------------------------------------- transfer (Response 15 step 2)

def _chain_tree(k, dims):
    """Pasting tree of cells of the given dimensions composed along cut k."""
    T = tuple(disc_tree(d - k - 1) for d in dims)
    for _ in range(k):
        T = (T,)
    return T

def _gcoh(G, k, dims, cells, lhs, rhs):
    """The coherence lhs -> rhs over the chain pasting context of `cells`
    along cut k; lhs, rhs are functions of the context's maximal variables."""
    P = tree_ctx(_chain_tree(k, dims))
    mx = maximal_vars(P)
    xs = [v(i) for i in mx]
    a, b = lhs(P, xs), rhs(P, xs)
    A = infer(P, a)
    assert A == infer(P, b), 'generic coherence: ends not parallel'
    return ('coh', P, arr(A, a, b), sub_from(P, G, dict(zip(mx, cells))))

def _vchain(G, n, cells):
    w = cells[0]
    for c in cells[1:]:
        w = comp2(G, n, w, c)
    return w

def _unit(G, n, k, x, back=False):
    """x -> x *_k 1 (or back), x an n-cell, 1 the identity on its k-target."""
    import rc_oracle as R
    def one(P, xs):
        y = xs[0]
        z = y
        for _ in range(n - k):
            z = tgt(P, z)
        idz = z
        while tdim_tm(P, idz) < k + 1:
            idz = R.identity(P, idz)
        return comp2(P, k, y, idz)
    l, r = (lambda P, xs: xs[0]), one
    if back:
        l, r = r, l
    return _gcoh(G, 0, [n], [x], l, r)

def _inverses(G, K, rec):
    """K^-1 and the cancellation pair 1 -> K K^-1, K K^-1 -> 1."""
    import rc_inverse as I
    Ki = I.inverse(G, K)
    if Ki is None:
        return None
    BK = infer(G, K)
    if infer(G, Ki) != arr(BK[1], BK[3], BK[2]):
        return None
    kap = I.cancel(G, K, rec)
    if kap is None:
        return None
    kapi = I.inverse(G, kap)
    Bk = infer(G, kap)
    if kapi is None or infer(G, kapi) != arr(Bk[1], Bk[3], Bk[2]):
        kapi = rec(G, Bk[1], Bk[3], Bk[2])
        if kapi is None:
            return None
    return Ki, kapi, kap

def strip_right(G, n, t, u, K, V, rec):
    """From V : t *_{n-1} K -> u *_{n-1} K (t, u n-cells, K an invertible
    n-cell) to t -> u:  t -> t 1 -> t (K K^-1) -> (t K) K^-1 -> (u K) K^-1
    -> u (K K^-1) -> u 1 -> u."""
    r = _inverses(G, K, rec)
    if r is None:
        return None
    Ki, kapi, kap = r
    m = n - 1
    assoc = lambda x, back=False: _gcoh(G, m, [n, n, n], [x, K, Ki],
        *((lambda P, xs: comp2(P, m, xs[0], comp2(P, m, xs[1], xs[2])),
           lambda P, xs: comp2(P, m, comp2(P, m, xs[0], xs[1]), xs[2]))[::(-1 if back else 1)]))
    steps = [_unit(G, n, m, t), comp2(G, m, t, kapi), assoc(t),
             comp2(G, m, V, Ki),
             assoc(u, True), comp2(G, m, u, kap), _unit(G, n, m, u, True)]
    return _vchain(G, n, steps)

def strip_lower(G, n, t, u, A, V, rec):
    """From V : t *_{n-2} A -> u *_{n-2} A (A an invertible (n-1)-cell on the
    (n-2)-target p of t, u) to t -> u. With c^-1 : 1_p -> A A^-1 and
    K = y' *_{n-2} c^-1, the interchange of t with c^-1 gives
    (t 1) *_{n-1} K -> (y c^-1) *_{n-1} (t (A A^-1)); regroup, apply V, and
    come back for u; then strip K by strip_right and remove the units."""
    import rc_inverse as I
    k = n - 2
    Ai = I.inverse(G, A)
    if Ai is None:
        return None
    c = I.cancel(G, A, rec)                      # A A^-1 -> 1_p
    if c is None:
        return None
    ci = I.inverse(G, c)
    Bc = infer(G, c)
    if ci is None or infer(G, ci) != arr(Bc[1], Bc[3], Bc[2]):
        ci = rec(G, Bc[1], Bc[3], Bc[2])
        if ci is None:
            return None
    y, y2 = src(G, t), tgt(G, t)
    K = comp2(G, k, y2, ci)
    def inter(x, back=False):
        def lhs(P, xs):
            X, C = xs
            return comp2(P, n - 1, comp2(P, k, X, src(P, C)), comp2(P, k, tgt(P, X), C))
        def rhs(P, xs):
            X, C = xs
            return comp2(P, n - 1, comp2(P, k, src(P, X), C), comp2(P, k, X, tgt(P, C)))
        return _gcoh(G, k, [n, n], [x, ci], *((lhs, rhs)[::(-1 if back else 1)]))
    def assoc(x, back=False):
        l = lambda P, xs: comp2(P, k, xs[0], comp2(P, k, xs[1], xs[2]))
        r = lambda P, xs: comp2(P, k, comp2(P, k, xs[0], xs[1]), xs[2])
        return _gcoh(G, k, [n, n - 1, n - 1], [x, A, Ai], *((l, r)[::(-1 if back else 1)]))
    yc = comp2(G, k, y, ci)
    inner = _vchain(G, n, [assoc(t), comp2(G, k, V, Ai), assoc(u, True)])
    V2 = _vchain(G, n, [inter(t), comp2(G, n - 1, yc, inner), inter(u, True)])
    t1 = tgt(G, _unit(G, n, k, t))
    u1 = tgt(G, _unit(G, n, k, u))
    W = strip_right(G, n, t1, u1, K, V2, rec)
    if W is None:
        return None
    return _vchain(G, n, [_unit(G, n, k, t), W, _unit(G, n, k, u, True)])

def _pole(G, x, k, sign):
    """The k-dimensional pole of a term x."""
    while tdim_tm(G, x) > k:
        B = infer(G, x)
        x = B[2] if sign == '-' else B[3]
    return x

def _map_ty(B, f):
    if B == STAR:
        return B
    return arr(_map_ty(B[1], f), f(B[2]), f(B[3]))

def _plus_ty(B, plus):
    if B == STAR:
        return B
    return arr(_plus_ty(B[1], plus), plus(B[2]), plus(B[3]))
