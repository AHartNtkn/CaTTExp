    boundary1.subtract(m.chain(m.atom_boundary(m.TOP, -1, 1)))
    assert enumerator2.solve(boundary1) == signatures2

    noninner = sorted(e for e in edges if e[2] != "I")
    edge_index = {e: i for i, e in enumerate(noninner)}
    d_quotient, d_roots = generator_quotient(noninner, edge_index, disjoint, vertex_index, labels)
