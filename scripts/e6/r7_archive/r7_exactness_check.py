#!/usr/bin/env python3
"""Finite, dimension-separated quotient checks for the r6/r7 presentation.

Dependencies: the unmodified r6_endpoint_lifts_check.py and its JSON certificate,
and r7_kernel4_certificate.json, generated by r7_kernel4_check.py.

The unconditional raw result replaces exactly three selected fresh four-cells
by old W cells followed by elementary directed disjoint interchangers.

The quotient result is conditional on the explicit independent-letter
naturality four-cells in the kernel certificate.  It kills I in dimension
three and kills the disjoint/naturality four-cells.  It does not reverse I in
the raw category.  Exhaustive positive-chain enumeration proves exactness
through dimension three in the fixed pair of one-boundaries of the top atom.
All fifteen selected fresh four-cells then have old-W expressions with the
same actual three-boundaries in that quotient.  Equating a fresh four-cell
to that expression is an additional four-dimensional equation, not a
consequence of the already imposed inner-interchanger equations.

Run after r7_kernel4_check.py.  Python standard library only; do not use -O.
"""

