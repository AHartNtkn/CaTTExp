"""Export the critical-pair instances of the 2026-11-19 table (both orientations) and random
multi-redex terms from nbe_rewrite.py to src/CaTTExp/Gray/BiclosedNFData.agda, after checking each
in Python (well typed, overlapping, single normal form)."""
import importlib.util, random, os, sys
here=os.path.dirname(os.path.abspath(__file__))
spec=importlib.util.spec_from_file_location('m',os.path.join(here,'nbe_rewrite.py')); m=importlib.util.module_from_spec(spec); spec.loader.exec_module(m)
def x(i): return (('a','x%d'%i),)
def G(n,s,t): return ('g','g%d'%n,s,t)
def E(d,A,Z): return ('e',d,A,Z)
def K(d,A,Z,X,b): return ('k',d,A,Z,X,tuple(b))
e=(); 
def tr(l,q,r): return (l,q,r)
H=m.H
rows={}
# N/N
f=G(1,x(2)+x(1),x(3)); ka=K('L',x(2),x(3),x(1),[tr(e,f,e)])
g=G(2,H('L',x(2),x(3))+x(4),x(5)); kb=K('R',x(4),x(5),H('L',x(2),x(3)),[tr(e,g,e)])
rows['NN']=(x(0),[tr(e,G(0,x(0),x(1)),e),tr(e,ka,e),tr(e,kb,e)])
# N/beta shared curry
rows['Nbeta_curry']=(x(2)+x(0),[tr(x(2),G(0,x(0),x(1)),e),tr(x(2),ka,e),tr(e,E('L',x(2),x(3)),e)])
# N/beta shared evaluation
g2=G(3,x(3)+x(4),x(5)); kb2=K('R',x(4),x(5),x(3),[tr(e,g2,e)])
rows['Nbeta_eval']=(x(2)+x(1),[tr(x(2),ka,e),tr(e,E('L',x(2),x(3)),e),tr(e,kb2,e)])
# eta curry
geta=G(4,x(5),H('L',x(1),x(3)))
keta=K('L',x(1),x(3),x(5),[tr(x(1),geta,e),tr(e,E('L',x(1),x(3)),e)])
rows['Neta_right']=(x(0),[tr(e,G(5,x(0),x(5)),e),tr(e,keta,e)])
fb=G(6,H('L',x(1),x(3))+x(4),x(6)); kb3=K('R',x(4),x(6),H('L',x(1),x(3)),[tr(e,fb,e)])
rows['Neta_left']=(x(5),[tr(e,keta,e),tr(e,kb3,e)])
rows['betaeta_curry']=(x(1)+x(5),[tr(x(1),keta,e),tr(e,E('L',x(1),x(3)),e)])
ff=G(7,x(1)+x(6),x(3)); kin=K('L',x(1),x(3),x(6),[tr(e,ff,e)])
kout=K('L',x(1),x(3),x(5),[tr(x(1),G(8,x(5),x(6)),e),tr(x(1),kin,e),tr(e,E('L',x(1),x(3)),e)])
rows['betaeta_final']=(x(5),[tr(e,kout,e)])
def mf(F):
    out=[]
    for f in reversed(F):
        if f[0]=='a': out.append(f)
        elif f[0]=='L': out.append(('R',mf(f[2]),mf(f[1])))
        else: out.append(('L',mf(f[2]),mf(f[1])))
    return tuple(out)
def mq(q):
    if q[0]=='g': return ('g',q[1],mf(q[2]),mf(q[3]))
    sw={'L':'R','R':'L'}
    if q[0]=='e': return ('e',sw[q[1]],mf(q[2]),mf(q[3]))
    return ('k',sw[q[1]],mf(q[2]),mf(q[3]),mf(q[4]),tuple(mt(t) for t in q[5]))
def mt(t): return (mf(t[2]),mq(t[1]),mf(t[0]))
for k in list(rows):
    s,w=rows[k]; rows[k+'_mirror']=(mf(s),[mt(t) for t in w])
cases=[]
for k,(s,w) in rows.items():
    w=tuple(w); m.check(w,s)
    assert len(m.reducts(w))>=2, k
    nf=m.all_nfs(w); assert len(nf)==1, k
    cases.append((k,w))
random.seed(11); got=0
while got<12:
    src=m.rformula(); w=()
    for _ in range(random.randint(0,2)): w=m.gen_append(w,src)
    for _ in range(random.randint(2,6)): w=m.expand(w,src)
    if m.nodes(w)<=9 and len(set(m.reducts(w)))>=2 and len(m.all_nfs(w))==1:
        cases.append(('random%d'%got,w)); got+=1
atoms={}
def an(f): return int(f[1][1:])
def af(F):
    if not F: return '[]'
    return '('+' ∷ '.join(afa(f) for f in F)+' ∷ [])'
def afa(f):
    if f[0]=='a': return '(atom %d)'%an(f)
    if f[0]=='L': return '(lres %s %s)'%(af(f[1]),af(f[2]))
    return '(rres %s %s)'%(af(f[1]),af(f[2]))
def aq(q):
    if q[0]=='g': return '(gen %s %s %s)'%(q[1][1:],af(q[2]),af(q[3]))
    d='Ld' if q[1]=='L' else 'Rd'
    if q[0]=='e': return '(ev %s %s %s)'%(d,af(q[2]),af(q[3]))
    return '(cur %s %s %s %s %s)'%(d,af(q[2]),af(q[3]),af(q[4]),aw(q[5]))
def at(t): return '(tri %s %s %s)'%(af(t[0]),aq(t[1]),af(t[2]))
def aw(w):
    if not w: return '[]'
    return '('+' ∷ '.join(at(t) for t in w)+' ∷ [])'
out=['------------------------------------------------------------------------',
'-- Generated by scripts/d11/export_agda.py: the critical-pair rows of the',
'-- 2026-11-19 table (both orientations) and random multi-redex terms.',
'-- Each check: the term has at least two redex occurrences, and every',
'-- reduction order reaches a single normal form, which equals the one',
'-- computed independently in Python.',
'------------------------------------------------------------------------',
'module CaTTExp.Gray.BiclosedNFData where','','open import CaTTExp.Prelude','open import CaTTExp.Gray.BiclosedNF','']
for k,w in cases:
    nm=k.replace('_','-')
    out.append('%s : Word'%nm); out.append('%s = %s'%(nm,aw(w)))
    out.append('%s-overlaps : T (overlapping %s)'%(nm,nm)); out.append('%s-overlaps = tt'%nm)
    out.append('%s-confluent : T (confluentOn 30 %s)'%(nm,nm)); out.append('%s-confluent = tt'%nm)
    nf=next(iter(m.all_nfs(w)))
    out.append('-- normal form computed independently by nbe_rewrite.py')
    out.append('%s-nf : Word'%nm); out.append('%s-nf = %s'%(nm,aw(nf)))
    out.append('%s-agrees : T (allSame (%s-nf ∷ fst (nfs 30 %s)))'%(nm,nm,nm)); out.append('%s-agrees = tt'%nm); out.append('')
open(os.path.join(here,'..','..','src','CaTTExp','Gray','BiclosedNFData.agda'),'w').write('\n'.join(out))
print(len(cases),'cases exported')
