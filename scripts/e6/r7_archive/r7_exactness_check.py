    signature_index2 = {sig: i for i, sig in enumerate(signatures2)}
    vertex_index = {w: signature_index2[m.signature(m.word_chain(w))] for w in vertices}
    # Independent proof that this is the entire relevant tableau 2-cell set.
    enumerator2 = PositiveChainEnumerator(2, 6)
