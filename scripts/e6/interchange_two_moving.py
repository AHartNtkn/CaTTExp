"""Ground degree five of P on zxy -> xyz, with advances on both x and y.

The left outer hom contains the two consecutive slots x,y; the right
contains one stationary slot z. Histories use a,b for xz,yz crossings,
X,Y for the ordered unary advances of the corresponding slots. Each
history interleaves ab, X^m, Y^n. Every positive block crossing has just
one row, so its (K15) expansions have a unique atomic order.

A primitive r transposes one of a,b,ab with a nonempty word of advances
on its moving slots. An inner comparison transposes two positive adjacent
histories on disjoint, spatially ordered intervals. Peeling off temporal
and spatial spectators and balancing the spatial gap gives precisely the
moves below. The right outer span has no varying history, ruling out t,
proper h, W and U_t. There is no input 4- or 5-globe, nor a third outer
factor for a triple. The r and inner equations therefore reduce to (10),
(14),(15),(20),(21); (9) is implemented by the spatial-gap normalization.
A literal chi can only use a,b or ab. There is no unrestricted inner
split. A 5-path is generated by delta, N_L, N_R, U_r in the indicated
lower contexts. For a composite 4-variation, paste the naturality
generators on its successive edges; the intermediate inner or outer
comparisons match with the fixed independent argument. Likewise a
temporal comparison on two composite 4-paths is the rectangular paste
of comparisons of their constituent edges. These pastes establish
reachability without imposing any 5-equation.

ground_all(m,n) returns the grounded presentation and the temporal window
Move of each edge. ground(start,finish) restricts to the exact 4-path
interval of two specified 3-boundaries. Positive weights are the
Response 4 weights, with c=m+n+6 and stationary operand of length one.
"""

from collections import Counter, defaultdict
from dataclasses import dataclass
from functools import cache
from itertools import combinations

from interchange_path_grading import History, i_faces, r_faces, word
from interchange_reachability import Edge, Path, Presentation, Rule, solve, verify


SUPPORT = {'a': frozenset('xz'), 'b': frozenset('yz'),
           'X': frozenset('x'), 'Y': frozenset('y')}
POSITIONS = ('zxy', 'xzy', 'xyz')
CROSSINGS = ('a', 'b', 'ab')


@dataclass(frozen=True, order=True)
class Move:
    kind: str
    lo: int
    mid: int
    hi: int

    def target(self, source):
        return source[:self.lo] + source[self.mid:self.hi] + source[self.lo:self.mid] + source[self.hi:]

    def shift(self, distance):
        return Move(self.kind, self.lo + distance, self.mid + distance, self.hi + distance)


def histories(m, n):
    length = m + n + 2
    for a, b in combinations(range(length), 2):
        remaining = [i for i in range(length) if i != a and i != b]
        for xs in combinations(remaining, m):
            letters = ['Y'] * length
            letters[a], letters[b] = 'a', 'b'
            for i in xs:
                letters[i] = 'X'
            yield ''.join(letters)


@cache
def slots(events):
    return frozenset().union(*(SUPPORT[e] for e in events))


def moves(history):
    for lo, mid, hi in combinations(range(len(history) + 1), 3):
        right, left = history[lo:mid], history[mid:hi]
        if right in CROSSINGS:
            allowed = {'a': 'X', 'b': 'Y', 'ab': 'XY'}[right]
            if all(event in allowed for event in left):
                yield Move('r', lo, mid, hi)
        order = POSITIONS[sum(e in 'ab' for e in history[:lo])]
        if max(order.index(s) for s in slots(left)) < min(order.index(s) for s in slots(right)):
            yield Move('i', lo, mid, hi)


def grade(history, move, constant):
    first = history[move.lo:move.mid]
    second = history[move.mid:move.hi]
    if move.kind == 'i':
        return len(first) * len(second)
    moment = second.count('X') - second.count('Y') if first == 'ab' else 0
    return constant * len(second) + moment


def edge_name(state, m):
    return f'{state}/{m.kind}{m.lo},{m.mid},{m.hi}'


def splits(state, m):
    first, second = state[m.lo:m.mid], state[m.mid:m.hi]
    if m.kind == 'r' or first in CROSSINGS:
        for cut in range(m.mid + 1, m.hi):
            yield '10' if m.kind == 'r' else '20', (
                Move(m.kind, m.lo, m.mid, cut),
                Move(m.kind, m.lo + cut - m.mid, cut, m.hi),
            )
    if m.kind == 'i' and second in CROSSINGS:
        for cut in range(m.lo + 1, m.mid):
            yield '21', (Move('i', cut, m.mid, m.hi),
                         Move('i', m.lo, cut, cut + m.hi - m.mid))


def walk(source, sequence):
    names = []
    state = source
    for operation in sequence:
        names.append(edge_name(state, operation))
        state = operation.target(state)
    return Path(source, tuple(names))


def ground_rules(state, active):
    """Every listed rule includes its lower whiskers; top whiskers are implicit."""
    def rule(name, lhs, rhs, equation=False):
        source = walk(state, lhs)
        target = walk(state, rhs)
        return Rule(f'{name} {source.edges} {target.edges}', source, target, equation)

    for outer in active:
        lo, mid, hi = outer.lo, outer.mid, outer.hi
        first, second = state[lo:mid], state[mid:hi]
        for law, sequence in splits(state, outer):
            yield rule(law, (outer,), sequence, True)
        if outer.kind == 'r' and first == 'ab':
            if set(second) == {'X'}:
                yield rule('14', (outer,), (
                    Move('i', lo + 1, mid, hi), Move('r', lo, lo + 1, hi - 1)), True)
            if set(second) == {'Y'}:
                yield rule('15', (outer, Move('i', lo, lo + len(second), hi - 1)),
                           (Move('r', lo + 1, mid, hi),), True)
        for inner in active:
            if outer.hi <= inner.lo:
                yield rule('delta', (inner, outer), (outer, inner))
            if mid <= inner.lo and inner.hi <= hi:
                # The left spatial operand varies in (26), or in (28).
                yield rule('N_L' if outer.kind == 'i' else 'U_r',
                           (outer, inner.shift(lo - mid)), (inner, outer))
            if outer.kind == 'i' and lo <= inner.lo and inner.hi <= mid:
                # In (27) the right variation comes first on the source.
                yield rule('N_R', (inner, outer), (outer, inner.shift(hi - mid)))


@cache
def ground_all(m, n):
    vertices = list(histories(m, n))
    edges, metadata, rules = {}, {}, []
    for state in vertices:
        active = list(moves(state))
        for move in active:
            name = edge_name(state, move)
            edges[name] = Edge(state, move.target(state), grade(state, move, m+n+6))
            metadata[name] = move
        rules.extend(ground_rules(state, active))
    return Presentation(vertices, edges, rules), metadata


def reachable(start, neighbors):
    found, pending = {start}, [start]
    while pending:
        for other in neighbors[pending.pop()]:
            if other not in found:
                found.add(other)
                pending.append(other)
    return found


def ground(start, finish):
    presentation, metadata = ground_all(start.count('X'), start.count('Y'))
    assert start in presentation.vertices and finish in presentation.vertices
    outgoing, incoming = defaultdict(set), defaultdict(set)
    for edge in presentation.edges.values():
        outgoing[edge.source].add(edge.target)
        incoming[edge.target].add(edge.source)
    vertices = reachable(start, outgoing) & reachable(finish, incoming)
    assert finish in vertices
    edges = {n: e for n, e in presentation.edges.items() if e.source in vertices and e.target in vertices}
    rules = [r for r in presentation.rules.values()
             if all(name in edges for name in r.source.edges + r.target.edges)]
    return Presentation(vertices, edges, rules), {n: metadata[n] for n in edges}


def verify_move(source, move):
    """Execute both faces on the typed 2-word, including all spectators."""
    events = {'a': ('z', 'x'), 'b': ('z', 'y'), 'X': ('x',), 'Y': ('y',)}
    chronological_prefix = tuple(events[e] for e in source[:move.lo])
    chronological_suffix = tuple(events[e] for e in source[move.hi:])
    prefix = History(word('zxy'), chronological_prefix)
    state = prefix.end
    names = ''.join(name for name, _ in state)
    first = source[move.lo:move.mid]
    second = source[move.mid:move.hi]
    if move.kind == 'i':
        left = min(names.index(slot) for slot in slots(second))
        cut = min(names.index(slot) for slot in slots(first))
        right = max(names.index(slot) for slot in slots(first)) + 1
        varying_left = History(state[left:cut], tuple(events[e] for e in second))
        varying_right = History(state[cut:right], tuple(events[e] for e in first))
        faces = i_faces(varying_left, varying_right)
    else:
        left = names.index('z')
        right = left + 1 + len(first)
        varying_left = History(state[left+1:right], tuple(events[e] for e in second))
        faces = r_faces(varying_left, state[left:left+1])
    for face, expected in zip(faces, (source, move.target(source))):
        padded = prefix.then(face.pad(state[:left], state[right:]))
        full = padded.then(History(padded.end, chronological_suffix))
        assert full.events == tuple(events[e] for e in expected)
        assert full.end == (('x', source.count('X')), ('y', source.count('Y')), ('z', 0))


def check_rectangle(start, finish, inputs, required_families):
    # The first two moves are A,B in the early half, the last two C,D in
    # the late half. Test the contextual path CDAB -> CADB and its reverse.
    presentation, _ = ground(start, finish)
    a, b, c, d = inputs
    source = walk(start, (c, d, a, b))
    target = walk(start, (c, a, d, b))
    forward = solve(presentation, source, target)
    reverse = solve(presentation, target, source)
    assert forward.reachable and verify(presentation, source, target, forward)
    assert not reverse.reachable and verify(presentation, target, source, reverse)
    used = Counter(step.rule.split()[0] for path in reverse.visited
                   for step, _ in presentation.successors(path))
    for family, expected in required_families.items():
        assert used[family] == expected
    print(f'{start} -> {finish}: {len(presentation.vertices)} 3-states, '
          f'{len(presentation.edges)} 4-edges, {len(presentation.rules)} rules; '
          f'{len(forward.steps)}-step forward, {len(reverse.visited)} paths in reverse cut, '
          f'cut transitions {dict(sorted(used.items()))}.')


def check():
    whole, metadata = ground_all(2, 2)
    for name, edge in whole.edges.items():
        verify_move(edge.source, metadata[name])
    print(f'Two moving slots with two advances each: {len(whole.vertices)} histories, '
          f'{len(whole.edges)} face-checked 4-edges, {len(whole.rules)} ground rules.')
    early = (Move('r', 0, 1, 2), Move('r', 1, 2, 3))
    late = (Move('r', 3, 4, 5), Move('r', 4, 5, 6))
    check_rectangle('aXXbYY', 'XXaYYb', early + late, {'15': 12, '21': 8})
    check_rectangle('YaXbYY', 'XaYYYb', (Move('i', 0, 1, 3), Move('r', 0, 1, 2)) + late,
                    {'N_L': 3})
    check_rectangle('aXXbYX', 'XXaXYb', early + (Move('r', 3, 4, 5), Move('i', 3, 5, 6)),
                    {'N_R': 3})
    check_rectangle('abYXYYX', 'XYabXYY',
                    (Move('r', 0, 2, 4), Move('i', 0, 1, 2),
                     Move('i', 5, 6, 7), Move('i', 4, 5, 6)),
                    {'U_r': 2})


if __name__ == '__main__':
    check()
