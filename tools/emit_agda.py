"""Emit a term with hash-consed top-level Agda definitions and a check that
the certified checker infers the expected type."""
from catt import *

def emit(modname, G, K, expected_ty, comment=''):
    defs, names = [], {}
    def nm_ctx(P):
        key = ('ctx', P)
        if key not in names:
            body = 'ε'
            for A in P:
                body += ' ▸ ' + ty(A)
            names[key] = 'c%d' % len(names)
            defs.append('%s : Ctx\n%s = %s\n' % (names[key], names[key], body))
        return names[key]
    def tm(t):
        if t[0] == 'v':
            return '(v %d)' % t[1]
        key = ('tm', t)
        if key not in names:
            P = nm_ctx(t[1]); A = ty(t[2]); s = ' ∷ '.join(tm(u) for u in t[3])
            nm = 't%d' % len(names)
            names[key] = nm
            defs.append('%s : Tm\n%s = coh %s %s ⟪ %s ∷ [] ⟫\n' % (nm, nm, P, A, s))
        return names[key]
    def ty(A):
        if A == STAR: return '⋆'
        return '(arr %s %s %s)' % (ty(A[1]), tm(A[2]), tm(A[3]))
    k = tm(K); g = nm_ctx(G); e = ty(expected_ty)
    out = ['-- Generated by tools/emit_agda.py. ' + comment,
           'module %s where' % modname, '',
           'open import CaTTExp.Prelude', 'open import CaTTExp.Pure', '',
           'v : Nat → Tm', 'v = var', '']
    out += defs
    out += ['expected : Ty', 'expected = %s' % e, '',
            '-- The certified checker accepts the term, at exactly the expected type.',
            'result : Σ Ty (%s ⊢tm %s ∶_)' % (g, k),
            'result = from-just (infer %s %s)' % (g, k), '',
            'type-is-expected : fst result ≡ expected',
            'type-is-expected = refl', '']
    return '\n'.join(out)
