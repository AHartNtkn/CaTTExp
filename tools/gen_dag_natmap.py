#!/usr/bin/env python3
"""Generate src/CaTTExp/Dag/NatMap.agda: maps Nat → Nat (0 = absent)
as tries of 16-field buckets (CaTTExp.Dag.Trie).

Agda's evaluator spends about a kilobyte on every trie node, so a table
with one node per entry costs several kilobytes per entry. A bucket holds
16 consecutive keys in one constructor, which cuts this by an order of
magnitude. Soundness does not depend on the layout: lookupN re-checks
that the bucket and field it read belong to the key it was asked for.
"""
import os

B = 16
out = []
w = out.append
w('------------------------------------------------------------------------')
w('-- Generated by tools/gen_dag_natmap.py. Do not edit.')
w('--')
w('-- Maps Nat → Nat, 0 meaning absent, as a trie (CaTTExp.Dag.Trie) of')
w('-- buckets of %d consecutive keys. The only fact used downstream is' % B)
w('-- lookupN-ok: if allN p accepts the map and p accepts 0 everywhere,')
w('-- then p accepts what lookupN returns, at the key that was asked for.')
w('------------------------------------------------------------------------')
w('open import CaTTExp.Prelude')
w('open import CaTTExp.Dag.Trie')
w('open import Agda.Builtin.Nat using (_*_; div-helper; mod-helper)')
w('')
w('module CaTTExp.Dag.NatMap where')
w('')
fs = ' '.join('n%d' % i for i in range(B))
w('data Bucket : Set where')
w('  bk : (%s : Nat) → Bucket' % fs)
w('')
w('bsize : Nat')
w('bsize = %d' % B)
w('')
w('getB : Nat → Bucket → Nat')
for i in range(B):
    w('getB %d (bk %s) = n%d' % (i, fs, i))
w('getB _ _ = 0')
w('')
w('NatMap : Set')
w('NatMap = Trie Bucket')
w('')
w('-- Key k lives in bucket k div %d, field k mod %d; the lookup checks' % (B, B))
w('-- that this is so (no arithmetic lemma needed downstream).')
w('lookB : Nat → Nat → Nat → Maybe Bucket → Nat')
w('lookB k q r nothing  = 0')
w('lookB k q r (just b) = if (bsize * q + r) ==ℕ k then getB r b else 0')
w('')
w('lookupN : Nat → NatMap → Nat')
w('lookupN k t = lookB k q r (lookupT q t)')
w('  where')
w('  q r : Nat')
w('  q = div-helper 0 %d k %d' % (B - 1, B - 1))
w('  r = mod-helper 0 %d k %d' % (B - 1, B - 1))
w('')
w('allB : (Nat → Nat → Bool) → Nat → Bucket → Bool')
w('allB p q (bk %s) =' % fs)
w('  ' + ' ∧ '.join('p (bsize * q + %d) n%d' % (i, i) for i in range(B)))
w('')
w('allN : (Nat → Nat → Bool) → NatMap → Bool')
w('allN p t = allT (allB p) t')
w('')
w('module _ (p : Nat → Nat → Bool) (p0 : ∀ k → T (p k 0)) where')
w('  getB-ok : ∀ q b r → T (allB p q b) → T (p (bsize * q + r) (getB r b))')
for i in range(B):
    # the i-th conjunct of allB
    proj = 'h'
    for j in range(i):
        proj = '(∧-snd {p (bsize * q + %d) n%d} %s)' % (j, j, proj)
    if i < B - 1:
        proj = '(∧-fst {p (bsize * q + %d) n%d} %s)' % (i, i, proj)
    w('  getB-ok q (bk %s) %d h = %s' % (fs, i, proj))
w('  getB-ok q (bk %s) %s h = p0 _' % (fs, '(suc ' * B + 'r' + ')' * B))
w('')
w('  lookB-ok : ∀ k q r m → (∀ b → m ≡ just b → T (allB p q b)) → T (p k (lookB k q r m))')
w('  lookB-ok k q r nothing  h = p0 k')
w('  lookB-ok k q r (just b) h = go ((bsize * q + r) ==ℕ k) refl')
w('    where')
w('    go : ∀ e → ((bsize * q + r) ==ℕ k) ≡ e → T (p k (if e then getB r b else 0))')
w('    go false _ = p0 k')
w('    go true  e = subst (λ x → T (p x (getB r b)))')
w('                   (==ℕ-sound (bsize * q + r) k (subst T (sym e) tt))')
w('                   (getB-ok q b r (h b refl))')
w('')
w('  lookupN-ok : ∀ t → T (allN p t) → ∀ k → T (p k (lookupN k t))')
w('  lookupN-ok t ok k =')
w('    lookB-ok k _ _ (lookupT (div-helper 0 %d k %d) t)' % (B - 1, B - 1))
w('      (λ b e → lookup-All {P = λ q b → T (allB p q b)} {k = div-helper 0 %d k %d} {t = t}' % (B - 1, B - 1))
w('                 (allT-All (allB p) t ok) e)')
w('')
path = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'CaTTExp', 'Dag', 'NatMap.agda')
with open(path, 'w') as f:
    f.write('\n'.join(out))
