    source2, target2 = vertex_index[m.SOURCE], vertex_index[m.TARGET]
    top_paths = [i for i, (s, t, p) in enumerate(paths) if (s, t) == (source2, target2)]
    signatures3 = sorted({path_chains[i] for i in top_paths})
