"""Emit a term with hash-consed top-level Agda definitions and a check that
the certified checker infers the expected type."""
from catt import *

def emit(modname, G, K, expected_ty, comment=''):
    defs, names = [], {}
    def nm_ctx(P):
        key = ('ctx', P)
        if key not in names:
            body = 'ε'
            for A in P:
                body += ' ▸ ' + ty(A)
            names[key] = 'c%d' % len(names)
            defs.append('%s : Ctx\n%s = %s\n' % (names[key], names[key], body))
        return names[key]
    def tm(t):
        if t[0] == 'v':
            return '(v %d)' % t[1]
        key = ('tm', t)
        if key not in names:
            P = nm_ctx(t[1]); A = ty(t[2]); s = ' ∷ '.join(tm(u) for u in t[3])
            nm = 't%d' % len(names)
            names[key] = nm
            defs.append('%s : Tm\n%s = coh %s %s ⟪ %s ∷ [] ⟫\n' % (nm, nm, P, A, s))
        return names[key]
    def ty(A):
        if A == STAR: return '⋆'
        return '(arr %s %s %s)' % (ty(A[1]), tm(A[2]), tm(A[3]))
    k = tm(K); g = nm_ctx(G); e = ty(expected_ty)
    out = ['-- Generated by tools/emit_agda.py. ' + comment,
           'module %s where' % modname, '',
           'open import CaTTExp.Prelude', 'open import CaTTExp.Pure', '',
           'v : Nat → Tm', 'v = var', '']
    out += defs
    out += ['expected : Ty', 'expected = %s' % e, '',
            '-- The certified checker accepts the term, at exactly the expected type.',
            'result : Σ Ty (%s ⊢tm %s ∶_)' % (g, k),
            'result = from-just (infer %s %s)' % (g, k), '',
            'type-is-expected : fst result ≡ expected',
            'type-is-expected = refl', '']
    return '\n'.join(out)


class Emitter:
    """Hash-consed module with several checks sharing definitions."""
    def __init__(self):
        self.defs, self.names, self.checks = [], {}, []
    def ctx(self, P):
        key = ('ctx', P)
        if key not in self.names:
            body = 'ε'
            for A in P:
                body += ' ▸ ' + self.ty(A)
            nm = 'c%d' % len(self.names)
            self.names[key] = nm
            self.defs.append('%s : Ctx\n%s = %s\n' % (nm, nm, body))
        return self.names[key]
    def tm(self, t):
        if t[0] == 'v':
            return '(v %d)' % t[1]
        key = ('tm', t)
        if key not in self.names:
            P = self.ctx(t[1]); A = self.ty(t[2]); s = self.sub(t[3])
            nm = 't%d' % len(self.names)
            self.names[key] = nm
            self.defs.append('%s : Tm\n%s = coh %s %s %s\n' % (nm, nm, P, A, s))
        return self.names[key]
    def sub(self, s):
        return '⟪ ' + ' ∷ '.join(self.tm(u) for u in s) + (' ∷ [] ⟫' if s else '[] ⟫')
    def ty(self, A):
        if A == STAR: return '⋆'
        return '(arr %s %s %s)' % (self.ty(A[1]), self.tm(A[2]), self.tm(A[3]))
    def check_type(self, label, G, t, A):
        g, k, e = self.ctx(G), self.tm(t), self.ty(A)
        self.checks.append(
            '%s-type : fst (from-just (infer %s %s)) ≡ %s\n%s-type = refl\n' % (label, g, k, e, label))
    def check_typed(self, label, G, t):
        g, k = self.ctx(G), self.tm(t)
        self.checks.append(
            '%s-typed : Σ Ty (%s ⊢tm %s ∶_)\n%s-typed = from-just (infer %s %s)\n' % (label, g, k, label, g, k))
    def check_eq(self, label, lhs_tm, sub, rhs_tm):
        self.checks.append(
            '%s-eq : %s [ %s ]tm ≡ %s\n%s-eq = refl\n' % (label, self.tm(lhs_tm), self.sub(sub), self.tm(rhs_tm), label))
    def module(self, modname, comment):
        out = ['-- Generated by tools/emit_agda.py. ' + comment,
               'module %s where' % modname, '',
               'open import CaTTExp.Prelude', 'open import CaTTExp.Pure', '',
               'v : Nat → Tm', 'v = var', '']
        return '\n'.join(out + self.defs + ['-- Checks (each by the certified checker or by refl).', ''] + self.checks)
